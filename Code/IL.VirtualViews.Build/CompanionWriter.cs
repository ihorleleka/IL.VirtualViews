using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace IL.VirtualViews.Build;

/// <summary>Produces ordinary Compile inputs; no analyzer or generator is required.</summary>
internal static class CompanionWriter
{
    public static string Create(INamedTypeSymbol type, string content)
    {
        var namespaces = new Stack<string>();
        for (var ns = type.ContainingNamespace; ns is { IsGlobalNamespace: false }; ns = ns.ContainingNamespace)
            namespaces.Push(Escape(ns.Name));
        var namespaceDeclaration = namespaces.Count == 0 ? "" : $"namespace {string.Join('.', namespaces)};\n\n";
        var literal = SymbolDisplay.FormatLiteral(content, quote: true);
        return "// <auto-generated/>\n#nullable enable\n" + namespaceDeclaration
            + $"public partial {(type.IsRecord ? "record class" : "class")} {Escape(type.Name)} : global::IL.VirtualViews.Interfaces.IVirtualView\n{{\n"
            + $"    public static string ViewContent => {literal};\n}}\n";
    }

    private static string Escape(string identifier) =>
        SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None
        || SyntaxFacts.GetContextualKeywordKind(identifier) != SyntaxKind.None ? "@" + identifier : identifier;
}
